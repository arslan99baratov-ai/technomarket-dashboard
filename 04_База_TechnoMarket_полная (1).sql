/* ============================================================
   САМОПРОВЕРКА. Сравните «Загружено» и «Должно_быть».
   Если хотя бы в одной строке написано ОШИБКА — файл скачался
   не полностью: скачайте его заново и выполните ещё раз.
   ============================================================ */
SELECT [Таблица], [Загружено], [Должно_быть],
       CASE WHEN [Загружено] = [Должно_быть] THEN N'OK'
            ELSE N'ОШИБКА — файл загрузился не полностью' END AS [Результат]
FROM (
    SELECT N'Customers' AS [Таблица], COUNT(*) AS [Загружено], 118 AS [Должно_быть] FROM dbo.Customers
    UNION ALL SELECT N'Products', COUNT(*), 57 FROM dbo.Products
    UNION ALL SELECT N'Orders', COUNT(*), 600 FROM dbo.Orders
    UNION ALL SELECT N'OrderItems', COUNT(*), 799 FROM dbo.OrderItems
) AS t;
GO

/* ============================================================
   КОНТРОЛЬНЫЕ ЦИФРЫ. С ними сверяйте карточки дашборда.
   В выручку берём только доставленные заказы.
   ============================================================ */
SELECT COUNT(DISTINCT o.OrderID) AS [Заказов_доставлено],
       SUM(i.Amount)             AS [Выручка],
       SUM(i.Amount) / COUNT(DISTINCT o.OrderID) AS [Средний_чек]
FROM dbo.Orders o
JOIN dbo.OrderItems i ON i.OrderID = o.OrderID
WHERE o.Status = N'Доставлен';
GO
