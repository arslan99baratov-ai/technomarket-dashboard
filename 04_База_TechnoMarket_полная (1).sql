IF OBJECT_ID('dbo.OrderItems', 'U') IS NOT NULL DROP TABLE dbo.OrderItems;
IF OBJECT_ID('dbo.Orders', 'U')     IS NOT NULL DROP TABLE dbo.Orders;
IF OBJECT_ID('dbo.Products', 'U')   IS NOT NULL DROP TABLE dbo.Products;
IF OBJECT_ID('dbo.Customers', 'U')  IS NOT NULL DROP TABLE dbo.Customers;
GO

CREATE TABLE dbo.Customers (
    CustomerID   NVARCHAR(10)  NOT NULL CONSTRAINT PK_Cust PRIMARY KEY,
    CustomerName NVARCHAR(100) NOT NULL,
    Gender       NVARCHAR(1)   NULL,
    City         NVARCHAR(50)  NULL,
    Region       NVARCHAR(50)  NULL,
    Phone        NVARCHAR(30)  NULL,
    Email        NVARCHAR(80)  NULL,
    RegDate      DATE          NULL
);
CREATE TABLE dbo.Products (
    ProductID   NVARCHAR(10)  NOT NULL CONSTRAINT PK_Prod PRIMARY KEY,
    ProductName NVARCHAR(100) NOT NULL,
    Category    NVARCHAR(50)  NOT NULL,
    Brand       NVARCHAR(50)  NULL,
    Price       INT           NOT NULL,
    Cost        INT           NOT NULL
);
CREATE TABLE dbo.Orders (
    OrderID     NVARCHAR(15) NOT NULL CONSTRAINT PK_Ord PRIMARY KEY,
    OrderDate   DATE         NOT NULL,
    CustomerID  NVARCHAR(10) NULL CONSTRAINT FK_Ord_Cust REFERENCES dbo.Customers (CustomerID),
    City        NVARCHAR(50) NULL,
    Region      NVARCHAR(50) NULL,
    PaymentType NVARCHAR(40) NULL,
    Status      NVARCHAR(20) NULL,
    Delivery    INT          NULL
);
CREATE TABLE dbo.OrderItems (
    OrderID   NVARCHAR(15) NOT NULL CONSTRAINT FK_It_Ord  REFERENCES dbo.Orders (OrderID),
    ProductID NVARCHAR(10) NOT NULL CONSTRAINT FK_It_Prod REFERENCES dbo.Products (ProductID),
    Quantity  INT          NOT NULL,
    Price     INT          NOT NULL,
    Discount  INT          NULL,
    Amount    INT          NOT NULL
);
GO

